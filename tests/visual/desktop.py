"""Real local UI checks. Missing credentials remain missing; no live responses are mocked."""
import json
import os
import re
from pathlib import Path
from playwright.sync_api import expect, sync_playwright

output = Path(".local-review")
base = os.environ.get("LOCAL_TEST_BASE_URL", "http://127.0.0.1:3000")
output.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width": 1440, "height": 960}, device_scale_factor=1)
    page.context.grant_permissions(["clipboard-read", "clipboard-write"], origin=base)
    failures = []
    page.on("pageerror", lambda error: failures.append(str(error)))
    page.goto(base, wait_until="networkidle", timeout=60000)
    page.get_by_test_id("greeting").wait_for(timeout=30000)
    page.screenshot(path=str(output / "desktop-light.png"), full_page=True)
    checks = []
    expect(page.get_by_test_id("setup-notice")).to_have_count(0)
    page.get_by_test_id("composer-menu").click()
    expect(page.get_by_role("menuitem", name="添加图片")).to_be_disabled()
    expect(page.get_by_role("menuitemcheckbox", name="联网搜索")).to_be_disabled()
    page.keyboard.press("Escape")
    composer = page.get_by_test_id("multimodal-input")
    composer.fill("当前标签页中的草稿")
    page.reload(wait_until="networkidle")
    expect(page.get_by_test_id("multimodal-input")).to_have_value("当前标签页中的草稿")
    page.get_by_role("button", name=re.compile("^新对话")).first.click()
    expect(page.get_by_test_id("multimodal-input")).to_have_value("")
    checks.append("简洁首页、缺少存储禁用图片、刷新恢复草稿")
    page.get_by_test_id("user-nav-button").click()
    page.get_by_role("menuitem", name="设置", exact=True).click()
    dialog = page.get_by_role("dialog")
    page.get_by_role("tab", name="技能", exact=True).click()
    expect(dialog.get_by_text("investigate-content", exact=True)).to_be_visible()
    page.get_by_role("tab", name="技能", exact=True).press("ArrowLeft")
    expect(dialog.get_by_text("待配置密钥", exact=True)).to_be_visible()
    expect(page.get_by_role("tab", name="工具连接")).to_be_focused()
    page.get_by_role("tab", name="常规", exact=True).click()
    expect(dialog.get_by_text("待配置存储", exact=True)).to_be_visible()
    dialog.get_by_role("button", name="复制配置模板", exact=True).click()
    template = page.evaluate("navigator.clipboard.readText()")
    assert "AI_GATEWAY_API_KEY=\n" in template and "TAVILY_API_KEY=\n" in template
    assert "BLOB_READ_WRITE_TOKEN=" in template and "POSTGRES_URL=" not in template and "AUTH_SECRET=" not in template
    page.screenshot(path=str(output / "capabilities.png"), full_page=True)
    dialog.get_by_role("button", name="深色", exact=True).click()
    expect(page.locator("html")).to_have_class("dark")
    page.keyboard.press("Escape")
    expect(dialog).not_to_be_visible()
    page.screenshot(path=str(output / "desktop-dark.png"), full_page=True)
    checks.append("技能配置、真实能力状态、键盘切换、深色主题")
    composer = page.get_by_test_id("multimodal-input")
    expect(page.get_by_test_id("greeting")).to_be_visible()
    composer.fill("第一行")
    composer.press("Shift+Enter")
    composer.press("X")
    expect(composer).to_have_value("第一行\nX")
    composer.evaluate("e => e.dispatchEvent(new KeyboardEvent('keydown', {key: 'Enter', isComposing: true, bubbles: true}))")
    expect(page.get_by_test_id("greeting")).to_be_visible()
    checks.append("换行、中文输入法不误提交")
    composer.fill("字" * 32001)
    page.get_by_test_id("send-button").click()
    expect(page.get_by_test_id("greeting")).to_be_visible()
    expect(composer).to_have_value("字" * 32001)
    checks.append("超长输入提示且保留草稿")
    composer.fill("/这是以斜线开头的正文，不是终端命令")
    page.get_by_test_id("send-button").click()
    expect(page.get_by_test_id("toast").filter(has_text="尚未配置模型密钥")).to_be_visible(timeout=20000)
    expect(page.get_by_test_id("stop-button")).not_to_be_visible()
    expect(page.get_by_role("alert").filter(has_text="这一轮还没有完成")).to_be_visible()
    page.get_by_role("button", name="恢复刚才的输入", exact=True).click()
    expect(page.get_by_test_id("multimodal-input")).to_have_value("/这是以斜线开头的正文，不是终端命令")
    # This turn was rejected before persistence; an edit must fail safely and keep its draft.
    page.get_by_test_id("message-user").last.hover()
    page.get_by_test_id("message-edit-button").last.click()
    page.get_by_test_id("multimodal-input").fill("修改提交失败时必须保留的草稿")
    page.get_by_test_id("send-button").click()
    expect(page.locator("[data-sonner-toast]").filter(has_text="修改没有提交")).to_be_visible(timeout=20000)
    expect(page.get_by_test_id("multimodal-input")).to_have_value("修改提交失败时必须保留的草稿")
    checks.append("消息修改失败时保留编辑状态与草稿")
    page.get_by_role("button", name=re.compile("^新对话")).first.click()
    expect(page.get_by_test_id("greeting")).to_be_visible()
    expect(page.get_by_test_id("multimodal-input")).to_have_value("")
    page.get_by_test_id("multimodal-input").fill("应被快捷键清空")
    page.keyboard.press("Control+Shift+O")
    expect(page.get_by_test_id("multimodal-input")).to_have_value("")
    checks.append("缺少密钥明确报错、新对话重置、快捷键")
    page.get_by_role("button", name="收起侧栏", exact=True).click()
    page.get_by_role("button", name="打开侧栏", exact=True).click()
    page.get_by_test_id("user-nav-button").click()
    page.get_by_role("menuitem", name="设置", exact=True).click()
    page.get_by_role("dialog").get_by_role("button", name="浅色", exact=True).click()
    page.keyboard.press("Escape")
    page.reload(wait_until="networkidle")
    expect(page.locator("html")).to_have_class("light")
    checks.append("侧栏收放、主题持久化")
    page.set_viewport_size({"width": 390, "height": 844})
    expect(page.get_by_role("button", name="打开侧栏", exact=True)).to_be_visible()
    expect(page.get_by_test_id("multimodal-input")).to_be_visible()
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth"), "mobile horizontal overflow"
    page.screenshot(path=str(output / "mobile-light.png"), full_page=True)
    page.get_by_role("button", name="打开侧栏", exact=True).click()
    expect(page.get_by_role("button", name="搜索对话", exact=True)).to_be_visible()
    page.get_by_role("button", name="搜索对话", exact=True).click()
    expect(page.get_by_role("textbox", name="搜索历史标题")).to_be_visible()
    page.keyboard.press("Escape")
    page.keyboard.press("Escape")
    expect(page.get_by_test_id("multimodal-input")).to_be_visible()
    checks.append("移动端布局、抽屉、搜索入口、无横向溢出")
    assert not failures, failures
    print(json.dumps({"title": page.title(), "checks": checks, "pageErrors": failures}, ensure_ascii=False))
    browser.close()
